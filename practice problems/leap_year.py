# Take a year as input and check whether it is a **leap year or not**.

# Example:

# Enter year: 2024
# Leap Year

# **Hint:** Use `%` and `if/elif/else`.

print("=== WELCOME ===")
year = int(input("Enter your year :"))
if(year % 4 == 0 ):
    print("The year is a leap year")
else :
    print("The year is not leap year")
