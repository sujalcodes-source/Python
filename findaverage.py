# Write a program that:

# 1. Uses a `for` loop to add all the numbers.
# 2. Finds how many numbers are in the list.
# 3. Calculates the **average**.
# 4. Prints the average.

# Expected output:

# ```text
# The average is 30.0
# ```

# ### 📚 Topics used

# * List
# * `for` loop
# * Accumulator variable
# * Counter variable
# * Division `/`

numbers = [10, 20, 30, 40, 50]
count = 0
av_num = 5
for number in numbers:
    average = number/av_num
    count +=1
print(average)

